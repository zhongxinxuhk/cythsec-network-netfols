var moduleByKey = func() map[string]Module {
	result := make(map[string]Module, len(Modules))
	for _, module := range Modules {
		result[module.Key] = module
	}
	return result
}()

// LookupModule 按键返回目录项。
func LookupModule(key string) (Module, bool) { module, ok := moduleByKey[key]; return module, ok }
