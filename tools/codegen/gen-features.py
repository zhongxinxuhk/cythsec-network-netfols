#!/usr/bin/env python3
"""CYS-TRF-028: generate versioned Rust/Python feature layouts from one registry."""
import argparse
import difflib
import json
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
RUST = 'dataplane/traffic-engine/src/feature/schema_gen.rs'
PYTHON = 'ml/training/features/schema_gen.py'


def validate(doc):
    if not isinstance(doc, dict):
        raise ValueError('registry must be an object')
    if type(doc.get('schema_version')) is not int or not 0 < doc['schema_version'] <= 2**32 - 1:
        raise ValueError('schema_version must be a positive u32')
    if doc.get('value_type') != 'f64':
        raise ValueError('value_type must be f64')
    if doc.get('iat_policy') != 'adjacent_arrival_saturating_zero_all_samples':
        raise ValueError('unsupported iat_policy')
    if type(doc.get('small_packet_max_len')) is not int or not 0 <= doc['small_packet_max_len'] <= 2**32 - 1:
        raise ValueError('small_packet_max_len must be u32')
    features = doc.get('features')
    if not isinstance(features, list) or not features:
        raise ValueError('features must be a nonempty ordered list')
    names = set()
    for i, item in enumerate(features):
        if not isinstance(item, dict):
            raise ValueError(f'features[{i}]: must be an object')
        name = item.get('name')
        if not isinstance(name, str) or not re.fullmatch(r'[a-z][a-z0-9_]*', name):
            raise ValueError(f'features[{i}]: invalid name')
        if name in names:
            raise ValueError(f'features[{i}]: duplicate {name}')
        names.add(name)
        if type(item.get('index')) is not int or item['index'] != i:
            raise ValueError(f'features[{i}] {name}: index must be contiguous and ordered')
        for field in ('unit', 'definition'):
            if not isinstance(item.get(field), str) or not item[field].strip():
                raise ValueError(f'features[{i}] {name}: missing {field}')
    return features


def render(doc):
    features = validate(doc)
    header = 'Generated by tools/codegen/gen-features.py; DO NOT EDIT.\nSource: configs/registry/features.json\n'
    rust = ''.join('// ' + line + '\n' for line in header.splitlines())
    rust += f"pub const FEATURE_SCHEMA_VERSION: u32 = {doc['schema_version']};\n"
    rust += f"pub const FEATURE_COUNT: usize = {len(features)};\n"
    rust += f"pub const SMALL_PACKET_MAX_LEN: u32 = {doc['small_packet_max_len']};\n"
    rust += 'pub mod idx {\n'
    for f in features:
        rust += ''.join('    /// ' + line + '\n' for line in (f["definition"] + ' Unit: ' + f["unit"]).splitlines())
        rust += f"    pub const {f['name'].upper()}: usize = {f['index']};\n"
    rust += '}\npub const FEATURE_NAMES: [&str; FEATURE_COUNT] = [\n'
    rust += ''.join(f'    "{f["name"]}",\n' for f in features)
    rust += '];\n'
    rust += f"pub const IDX_LAYOUT_CHECK: [(); FEATURE_COUNT] = [(); idx::{features[-1]['name'].upper()} + 1];\n"
    # Match cargo fmt deterministically, without modifying the working tree in --check mode.
    rust = subprocess.run(['rustfmt', '--edition', '2021'], input=rust, text=True,
                          capture_output=True, check=True).stdout
    py = ''.join('# ' + line + '\n' for line in header.splitlines())
    py += f"FEATURE_SCHEMA_VERSION = {doc['schema_version']}\nFEATURE_COUNT = {len(features)}\n"
    py += f"SMALL_PACKET_MAX_LEN = {doc['small_packet_max_len']}\n\n\nclass idx:\n"
    py += ''.join(f"    {f['name'].upper()} = {f['index']}\n" for f in features)
    py += '\n\nFEATURE_NAMES = (\n' + ''.join(f'    "{f["name"]}",\n' for f in features) + ')\n'
    py += '\nFEATURE_UNITS = ' + repr(tuple(f['unit'] for f in features)) + '\n'
    py += 'FEATURE_DEFINITIONS = ' + repr(tuple(f['definition'] for f in features)) + '\n'
    return {RUST: rust, PYTHON: py}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--root', type=Path, default=ROOT, help='isolated fixture root for self-tests')
    args = parser.parse_args()
    try:
        doc = json.loads((args.root / 'configs/registry/features.json').read_text())
        outputs = render(doc)
    except (ValueError, KeyError, OSError, subprocess.SubprocessError) as exc:
        print(f'feature registry invalid: {exc}', file=sys.stderr)
        return 2
    stale = False
    for relative, expected in outputs.items():
        path = args.root / relative
        actual = path.read_text() if path.exists() else ''
        if args.check:
            if actual != expected:
                stale = True
                print(''.join(difflib.unified_diff(actual.splitlines(True), expected.splitlines(True),
                                                   fromfile=relative, tofile='generated')), file=sys.stderr)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)
    if stale:
        print('feature bindings stale; run python3 tools/codegen/gen-features.py', file=sys.stderr)
        return 1
    print('✓ feature schema: Rust/Python bindings consistent')
    return 0


if __name__ == '__main__':
    sys.exit(main())
